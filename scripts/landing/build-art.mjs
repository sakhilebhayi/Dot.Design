#!/usr/bin/env node
// Builds the landing page's artwork from the REAL library: each picture is a real template (database/templates/*.php) run through the real
// TemplateInstantiator and drawn by the editor's own renderer (renderPageToSvgString) in headless Chrome, so the page shows exactly what the
// product makes. Output: public/landing/art/*.svg (inlined or fetched by the landing page) and resources/css/ds/landing-fonts.css (the
// @font-face rules for the typefaces those drawings use, lazy by nature: a face is fetched only when text in it is drawn).
// Usage: node scripts/landing/build-art.mjs        (re-run after the library, the engine or the example brand changes)
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { openHarness } from '../dev/qa/browser.mjs';
import { ROOT } from '../dev/qa/server.mjs';

// one real template per hero format (the keys are StartFormats keys), then the one used for the brand before and after
const HERO = {
    'instagram-post': 'ig-post-square-playful',
    'instagram-story': 'event-invitation-playful',
    poster: 'promo-poster-bold',
    flyer: 'flyer-a5-bold',
    presentation: 'brand-guidelines-clean',
    banner: 'sale-ad-bold',
    'business-card': 'business-card-dark',
    logo: 'logo-wordmark-bold',
};
const BRAND = 'sale-ad-bold';

const slugs = [...new Set([...Object.values(HERO), BRAND])];
const data = JSON.parse(execFileSync('php', ['scripts/landing/instantiate.php', slugs.join(',')], { cwd: ROOT, maxBuffer: 1 << 28 }).toString());

const out = resolve(ROOT, 'public/landing/art');
mkdirSync(out, { recursive: true });
const h = await openHarness({ width: 1400, height: 1000 });
const used = new Map();
const manifestOut = {}; // variant id -> {font, weight, italic, url}
try {
    const manifest = await h.chrome.eval('QA.manifest');
    const draw = async (name, slug, which) => {
        const t = data[slug];
        const page = t[which];
        const fmt = { width: t.width, height: t.height };
        await h.chrome.eval(`QA.ensure([QA.norm(${JSON.stringify(page)}, ${JSON.stringify(fmt)})])`);
        const specs = await h.chrome.eval(`QA.fonts.usedSpecs([QA.norm(${JSON.stringify(page)}, ${JSON.stringify(fmt)})])`);
        for (const s of specs) {
            const v = await h.chrome.eval(`QA.fonts.resolveVariant(${JSON.stringify(s.font)}, ${s.weight ?? 400}, ${!!s.italic})`);
            const entry = manifest.find((m) => m.key === s.font);
            const file = entry && entry.files[`${v.weight}${v.italic ? 'i' : ''}`];
            if (file) used.set(`${s.font}:${v.weight}:${v.italic}`, { font: s.font, weight: v.weight, italic: v.italic, url: file });
        }
        const svg = await h.chrome.eval(`QA.svg(${JSON.stringify(page)}, ${JSON.stringify(fmt)}, { placeholders: false, idPrefix: ${JSON.stringify(name + '-')} })`);
        writeFileSync(join(out, `${name}.svg`), svg + '\n');
        // the artwork's own colours (its fills), most used first, for the swatch strip on the page
        const counts = new Map();
        for (const m of svg.matchAll(/fill="(#[0-9a-fA-F]{6})"/g)) counts.set(m[1].toLowerCase(), (counts.get(m[1].toLowerCase()) || 0) + 1);
        manifestOut[name] = { template: slug, name: t.name, width: t.width, height: t.height, colors: [...counts.entries()].sort((a, b) => b[1] - a[1]).map(([c]) => c).slice(0, 5) };
        console.log(name, slug, which, Math.round(svg.length / 1024) + ' KB');
    };
    for (const [key, slug] of Object.entries(HERO)) await draw(key, slug, 'plain');
    // the closing section shows three of them again; separate ids so inlining one drawing twice never collides
    for (const key of ['instagram-post', 'poster', 'presentation']) await draw(`close-${key}`, HERO[key], 'plain');
    await draw('brand-before', BRAND, 'plain');
    await draw('brand-after', BRAND, 'branded');
} finally { h.close(); }
writeFileSync(join(out, 'manifest.json'), JSON.stringify(manifestOut, null, 1) + '\n');

const css = [...used.values()].sort((a, b) => (a.font + a.weight).localeCompare(b.font + b.weight)).map((u) =>
    `@font-face { font-family: "dd-${u.font}"; font-weight: ${u.weight}; font-style: ${u.italic ? 'italic' : 'normal'}; font-display: swap; src: url("/fonts/design/${u.url.replace(/^\/fonts\//, '')}") format("woff2"); }`);
writeFileSync(resolve(ROOT, 'resources/css/ds/landing-fonts.css'), `/* Generated by scripts/landing/build-art.mjs: the typefaces the landing artwork is drawn in (the library's own, self-hosted). */\n${css.join('\n')}\n`);
console.log(`${used.size} font faces`);
